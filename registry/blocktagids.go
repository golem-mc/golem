// mustBlockTag is BlockTagOf for a tag the server code names, where a tag the
// registry lacks is a typo rather than a version difference.
func mustBlockTag(tag string) BlockTagID {
	id := BlockTagOf(tag)
	if id == noBlockTag {
		panic("registry: unknown block tag " + tag)
	}
	return id
}
