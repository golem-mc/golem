// mustItemTag rejects a misspelled built-in tag at initialization.
func mustItemTag(tag string) ItemTagID {
	id := ItemTagOf(tag)
	if id == noItemTag {
		panic("registry: unknown item tag " + tag)
	}
	return id
}
