func TestFillPlatformSurvivesTeleportChunkStreaming(t *testing.T) {
	for _, fresh := range []bool{false, true} {
		name := "existing-view"
		if fresh {
			name = "new-view"
		}
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			cfg := config.Default()
			cfg.OnlineMode = false
			cfg.ViewDistance = config.MinDistance
			cfg.SimulationDistance = config.MinDistance
			if fresh {
				// Generate the seed-1 normal terrain live: copying a fixture would
				// miss a write racing generation. Only two minimum-size views load.
				cfg.LevelType = "normal"
				cfg.LevelSeed = "1"
			}
			srv, c := servertest.Join(t, cfg, "Builder", servertest.OpsListing(t, "Builder"), func(s *server.Server) {
				s.SetMoveChecks(true)
				if fresh {
					s.SetWorldSpawn(world.SpawnPos{X: 160, Y: 64, Z: 160})
				}
			})
			servertest.HoldTicks(t, srv)
			w := srv.OverworldWorld()
			if fresh && w.ChunkLoadedAt(0, 0) {
				t.Fatal("teleport destination was already generated by the join")
			}

			// Keep the client's final view, including a chunk snapshot that could
			// arrive after a block update and overwrite it.
			cells := make(map[[3]int32]uint16)
			var chats [][]byte
			chunks := make(map[world.ChunkPos]bool)
			see := func(id int32, data []byte) bool {
				switch id {
				case protocol.IDPlayChunkData:
					pos := fillPlatformChunk(t, data, cells)
					chunks[pos] = true
				case protocol.IDPlayBlockUpdate, protocol.IDPlaySectionBlocks:
					for _, ch := range servertest.BlockChangesIn(t, id, data) {
						cells[[3]int32{ch.X, ch.Y, ch.Z}] = ch.State
					}
				case protocol.IDPlaySystemChat:
					chats = append(chats, data)
				}
				return false
			}
			c.ChatCommand("gamemode creative")
			c.ChatCommand("tp @s 0.5 100 3.5 180 25")
			c.ReadTicks(srv, 0, see)
			if fresh {
				// /fill requires loaded corners. Wait only for the four platform
				// chunks, without advancing the game or waiting for the whole view.
				// The sender's generation runs independently of the held tick.
				timer := time.NewTimer(servertest.ChunksSettledTimeout)
				defer timer.Stop()
				for {
					beat := srv.ChunkBeat()
					if w.ChunkLoadedAt(-2, -2) && w.ChunkLoadedAt(-2, 4) &&
						w.ChunkLoadedAt(2, -2) && w.ChunkLoadedAt(2, 4) {
						break
					}
					select {
					case <-beat:
					case <-timer.C:
						t.Fatal("teleport destination did not generate")
					}
				}
			}
			c.ChatCommand("fill -2 99 -2 2 99 4 minecraft:stone")
			c.ChatCommand("setblock 0 100 0 minecraft:jukebox")
			c.ReadTicks(srv, 0, see)
			expectFillFeedback(t, c, chats, 35)

			wantChunks := int(2*c.ChunkRadius+1) * int(2*c.ChunkRadius+1)
			if fresh && len(chunks) < wantChunks {
				for id, data := range c.Stream() {
					see(id, data)
					if id == protocol.IDPlayChunkBatchFinished && len(chunks) >= wantChunks {
						break
					}
				}
			}
			servertest.AwaitChunksSettled(t, srv)
			c.ReadTicks(srv, 40, see)
			stone := servertest.BlockState(t, "minecraft:stone")
			for x := int32(-2); x <= 2; x++ {
				for z := int32(-2); z <= 4; z++ {
					if got := srv.BlockAt(x, 99, z); got != stone {
						t.Errorf("settled world (%d,99,%d) = %d, want stone %d", x, z, got, stone)
					}
					if got, ok := cells[[3]int32{x, 99, z}]; !ok || got != stone {
						t.Errorf("settled client (%d,99,%d) = %d (received %v), want stone %d", x, z, got, ok, stone)
					}
				}
			}
			jukebox := servertest.BlockState(t, "minecraft:jukebox")
			if got := srv.BlockAt(0, 100, 0); got != jukebox || cells[[3]int32{0, 100, 0}] != jukebox {
				t.Errorf("jukebox world/client = %d/%d, want %d", got, cells[[3]int32{0, 100, 0}], jukebox)
			}

			// A headless client has no gravity. Report a step into the platform
			// to exercise the server's collision check as well as the wire view.
			c.MoveToGrounded(0.5, 99.5, 3.5, 180, 25, false)
			got := servertest.ExpectTeleport(t, c)
			if got.X != 0.5 || got.Y != 100 || got.Z != 3.5 {
				t.Fatalf("platform collision returned player to %+v, want (0.5,100,3.5)", got)
			}
			c.ReadTicks(srv, 1, see)
			if pos := srv.PlayerPosition("Builder"); pos.Y != 100 {
				t.Errorf("settled player y = %v, want 100", pos.Y)
			}
		})
	}
}

// fillPlatformChunk applies the part of a chunk packet containing the platform.
// vanilla: ClientboundLevelChunkPacketData.STREAM_CODEC, LevelChunkSection.read
func fillPlatformChunk(t *testing.T, data []byte, cells map[[3]int32]uint16) world.ChunkPos {
	t.Helper()
	r := protocol.NewReader(data)
	pos := world.ChunkPos{X: r.ReadI32(), Z: r.ReadI32()}
	if pos.X < -1 || pos.X > 0 || pos.Z < -1 || pos.Z > 0 {
		return pos
	}
	for range r.ReadVarInt() {
		r.ReadVarInt() // heightmap type
		for range r.ReadVarInt() {
			r.ReadI64()
		}
	}
	sr := protocol.NewReader(r.ReadBytes(1 << 21))
	for y := int32(-64); y <= 96; y += 16 {
		sr.ReadI16() // non-air blocks
		sr.ReadI16() // fluids
		blocks := fillPlatformPalette(t, sr, 4096, 8)
		fillPlatformPalette(t, sr, 64, 3) // biomes
		if y != 96 {
			continue
		}
		for x := range int32(16) {
			for z := range int32(16) {
				for _, by := range []int32{99, 100} {
					cells[[3]int32{pos.X*16 + x, by, pos.Z*16 + z}] = blocks[(by&15)*256+z*16+x]
				}
			}
		}
	}
	if r.Err() != nil || sr.Err() != nil {
		t.Fatalf("platform chunk decode: %v / %v", r.Err(), sr.Err())
	}
	return pos
}

func fillPlatformPalette(t *testing.T, r *protocol.Reader, count, indirectMax int) []uint16 {
	t.Helper()
	width := int(r.ReadU8())
	out := make([]uint16, count)
	if width == 0 {
		state := uint16(r.ReadVarInt())
		for i := range out {
			out[i] = state
		}
		return out
	}
	var palette []uint16
	if width <= indirectMax {
		for range r.ReadVarInt() {
			palette = append(palette, uint16(r.ReadVarInt()))
		}
	}
	if width > 32 {
		t.Fatalf("invalid palette width %d", width)
	}
	perLong := 64 / width
	var packed uint64
	for i := range out {
		if i%perLong == 0 {
			packed = uint64(r.ReadI64())
		}
		value := (packed >> (i % perLong * width)) & ((1 << width) - 1)
		if palette != nil {
			if value >= uint64(len(palette)) {
				t.Fatalf("palette index %d outside %d entries", value, len(palette))
			}
			out[i] = palette[value]
		} else {
			out[i] = uint16(value)
		}
	}
	return out
}
