func TestEnchantOffersMatchTheJVM(t *testing.T) {
	for _, c := range enchantOracleCases {
		id, ok := registry.ItemID(c.item)
		if !ok {
			t.Fatalf("the registry does not name %s", c.item)
		}
		stack := protocol.ItemStack{ItemID: id, Count: 1}
		costs, clues, levels := EnchantOffers(int32(c.seed), c.bookcases, stack)
		if costs != c.costs || clues != c.clues || levels != c.levels {
			t.Errorf("%s seed %d shelves %d: costs %v clues %v levels %v, want %v %v %v",
				c.item, c.seed, c.bookcases, costs, clues, levels, c.costs, c.clues, c.levels)
		}
	}
}
