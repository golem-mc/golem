func runPackets(e *env) error {
	packets, err := e.ref.Packets()
	if err != nil {
		return err
	}
	f := e.file("protocol", "from packets.json of a vanilla {version} server")
	f.WriteString("// Packet IDs, specific to both the connection state and the direction. The In\n// suffix marks a serverbound packet whose ID collides with a clientbound one\n// in the same state.\nconst (\n")
	for i, c := range packetConsts {
		id, err := packets.ID(c.state, c.direction, c.packet)
		if err != nil {
			return fmt.Errorf("%s: %w", c.name, err)
		}
		if i > 0 && (c.state != packetConsts[i-1].state || c.direction != packetConsts[i-1].direction) {
			f.WriteString("\n")
		}
		f.Printf("\t%s = 0x%02X // %s %s %s\n", c.name, id, c.state, c.direction, c.packet)
	}
	f.WriteString(")\n")
	if err := e.emit("internal/protocol/packetids_gen.go", f); err != nil {
		return err
	}
	e.logf("packet IDs: %d", len(packetConsts))
	return nil
}
