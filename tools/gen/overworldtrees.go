package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/golem-mc/golem/tools/internal/vanilla"
)

func init() {
	register(generator{
		name: "overworld-trees",
		doc:  "internal/server/world/levelgen/overworld_trees.txt: the data pack's tree and huge mushroom features of the overworld",
		run:  runOverworldTrees,
	})
}

// treeRoots are the placed features of the overworld's decoration whose
// features grow trees or huge mushrooms. Each is read with everything its
// selectors reach.
var treeRoots = []string{
	"trees_windswept_savanna", "trees_sparse_jungle", "trees_badlands", "trees_jungle",
	"trees_savanna", "pale_garden_vegetation", "dark_forest_vegetation", "trees_flower_forest",
	"birch_tall", "trees_birch", "trees_birch_and_oak_leaf_litter", "trees_meadow",
	"trees_windswept_forest", "trees_old_growth_pine_taiga", "trees_old_growth_spruce_taiga",
	"trees_taiga", "trees_grove", "trees_windswept_hills", "trees_snowy", "trees_mangrove",
	"trees_swamp", "trees_water", "trees_plains", "trees_cherry", "trees_dappled_forest", "mushroom_island_vegetation",
	"bamboo_vegetation", "rooted_azalea_tree", "warm_ocean_vegetation",
	// The abandoned camps' tree pools name these as feature pool elements.
	"bamboo_in_structure", "birch_checked", "cherry_bees_005", "cherry_checked",
	"orange_poplar", "red_poplar", "yellow_poplar",
}

// treeConfiguredRoots are configured features that tree decorators place by
// name.
var treeConfiguredRoots = []string{"nylium_bonemeal", "pale_moss_patch"}

// placeableTypes are the configured feature types the server runs on loaded
// chunks for /place feature; every configured feature of one is kept, with
// what its selectors reach.
var placeableTypes = []string{
	"bamboo", "block_column", "fallen_tree", "huge_brown_mushroom", "huge_fungus", "huge_red_mushroom", "kelp",
	"multiface_growth", "random_boolean_selector", "random_selector", "root_system", "sea_pickle",
	"seagrass", "simple_block", "simple_random_selector", "tree", "vegetation_patch",
	"vines", "waterlogged_vegetation_patch",
}

// treeCollector reads the placed and configured features reachable from the
// roots: a configured feature's selectors name further placed features.
type treeCollector struct {
	dp         *vanilla.DataPack
	placed     map[string]json.RawMessage
	configured map[string]json.RawMessage
	providers  map[string]json.RawMessage
}

func runOverworldTrees(e *env) error {
	dp, err := e.ref.DataPack()
	if err != nil {
		return err
	}
	defer dp.Close()
	c := &treeCollector{dp: dp, placed: map[string]json.RawMessage{}, configured: map[string]json.RawMessage{}, providers: map[string]json.RawMessage{}}
	for _, r := range treeRoots {
		if err := c.addPlaced("minecraft:" + r); err != nil {
			return err
		}
	}
	for _, r := range treeConfiguredRoots {
		if err := c.addConfigured("minecraft:" + r); err != nil {
			return err
		}
	}
	files, err := vanilla.Files(dp, "minecraft/worldgen/feature", ".json")
	if err != nil {
		return err
	}
	for _, f := range files {
		name := "minecraft:" + strings.TrimSuffix(f, ".json")
		raw, err := c.read("feature", name)
		if err != nil {
			return err
		}
		var head struct {
			Type string `json:"type"`
		}
		if err := json.Unmarshal(raw, &head); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if slices.Contains(placeableTypes, strings.TrimPrefix(head.Type, "minecraft:")) {
			if err := c.addConfigured(name); err != nil {
				return err
			}
		}
	}
	providers, err := vanilla.Files(dp, "minecraft/worldgen/block_state_provider", ".json")
	if err != nil {
		return err
	}
	for _, file := range providers {
		name := "minecraft:" + strings.TrimSuffix(file, ".json")
		raw, err := c.read("block_state_provider", name)
		if err != nil {
			return err
		}
		c.providers[name] = raw
	}
	var out bytes.Buffer
	out.WriteString("# Generated by tools/gen overworld-trees from the vanilla " + e.ref.Version + " data pack. DO NOT EDIT.\n")
	for _, sec := range []struct {
		kind string
		m    map[string]json.RawMessage
	}{{"placed", c.placed}, {"configured", c.configured}, {"provider", c.providers}} {
		if sec.m == nil {
			continue
		}
		names := make([]string, 0, len(sec.m))
		for n := range sec.m {
			names = append(names, n)
		}
		slices.Sort(names)
		for _, n := range names {
			var compact bytes.Buffer
			if err := json.Compact(&compact, sec.m[n]); err != nil {
				return err
			}
			fmt.Fprintf(&out, "%s %s %s\n", sec.kind, n, compact.String())
		}
		e.logf("%s: %d", sec.kind, len(names))
	}
	return e.emitBytes("internal/server/world/levelgen/overworld_trees.txt", out.Bytes())
}

func (c *treeCollector) read(kind, name string) (json.RawMessage, error) {
	var raw json.RawMessage
	if err := vanilla.ReadJSON(c.dp, "minecraft/worldgen/"+kind+"/"+strings.TrimPrefix(name, "minecraft:")+".json", &raw); err != nil {
		return nil, err
	}
	return raw, nil
}

func (c *treeCollector) addPlaced(name string) error {
	if _, ok := c.placed[name]; ok {
		return nil
	}
	raw, err := c.read("placed_feature", name)
	if err != nil {
		return err
	}
	c.placed[name] = raw
	var p struct {
		Feature json.RawMessage `json:"feature"`
	}
	if err := json.Unmarshal(raw, &p); err != nil {
		return err
	}
	return c.addConfiguredRef(p.Feature)
}

// addConfiguredRef follows a configured feature given by name or inline.
func (c *treeCollector) addConfiguredRef(ref json.RawMessage) error {
	var name string
	if json.Unmarshal(ref, &name) == nil {
		return c.addConfigured(name)
	}
	var inline struct {
		Type    string          `json:"type"`
		Feature json.RawMessage `json:"feature"`
	}
	if err := json.Unmarshal(ref, &inline); err != nil {
		return err
	}
	if inline.Type != "" { // a configured feature written in place
		return c.follow("inline", ref)
	}
	return c.addConfiguredRef(inline.Feature)
}

// addPlacedRef follows a placed feature given by name or inline.
func (c *treeCollector) addPlacedRef(ref json.RawMessage) error {
	var name string
	if json.Unmarshal(ref, &name) == nil {
		return c.addPlaced(name)
	}
	var inline struct {
		Feature json.RawMessage `json:"feature"`
	}
	if err := json.Unmarshal(ref, &inline); err != nil {
		return err
	}
	return c.addConfiguredRef(inline.Feature)
}

func (c *treeCollector) addConfigured(name string) error {
	if _, ok := c.configured[name]; ok {
		return nil
	}
	raw, err := c.read("feature", name)
	if err != nil {
		return err
	}
	c.configured[name] = raw
	if err := c.follow(name, raw); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	return nil
}

// follow adds the features a configured feature's selectors name.
func (c *treeCollector) follow(name string, raw json.RawMessage) error {
	// vanilla: Feature.DIRECT_CODEC dispatches the concrete feature's fields
	// directly.
	var header struct {
		Type string `json:"type"`
	}
	if err := json.Unmarshal(raw, &header); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	var cf struct {
		Default      json.RawMessage `json:"default"`
		FeatureTrue  json.RawMessage `json:"feature_true"`
		FeatureFalse json.RawMessage `json:"feature_false"`
		Features     json.RawMessage `json:"features"`
		Vegetation   json.RawMessage `json:"vegetation_feature"`
		Feature      json.RawMessage `json:"feature"`
	}
	if err := json.Unmarshal(raw, &cf); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	var refs []json.RawMessage
	switch header.Type {
	case "minecraft:random_selector":
		refs = append(refs, cf.Default)
		var entries []struct {
			Feature json.RawMessage `json:"feature"`
		}
		if err := json.Unmarshal(cf.Features, &entries); err != nil {
			return err
		}
		for _, f := range entries {
			refs = append(refs, f.Feature)
		}
	case "minecraft:simple_random_selector", "minecraft:sequence", "minecraft:overlay":
		if err := json.Unmarshal(cf.Features, &refs); err != nil {
			// vanilla: PlacedFeature.LIST_CODEC permits a single holder too.
			refs = []json.RawMessage{cf.Features}
		}
	case "minecraft:weighted_random_selector":
		var entries []struct {
			Data json.RawMessage `json:"data"`
		}
		if err := json.Unmarshal(cf.Features, &entries); err != nil {
			return err
		}
		for _, entry := range entries {
			refs = append(refs, entry.Data)
		}
	case "minecraft:random_boolean_selector":
		refs = append(refs, cf.FeatureTrue, cf.FeatureFalse)
	case "minecraft:root_system":
		refs = append(refs, cf.Feature)
	case "minecraft:vegetation_patch", "minecraft:waterlogged_vegetation_patch":
		refs = append(refs, cf.Vegetation)
	}
	for _, r := range refs {
		if err := c.addPlacedRef(r); err != nil {
			return err
		}
	}
	return nil
}
