import java.io.PrintWriter;
import java.lang.reflect.Method;
import net.minecraft.core.Holder;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.level.biome.MultiNoiseBiomeSource;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.Random;
import java.util.concurrent.Callable;
import net.minecraft.SharedConstants;
import net.minecraft.core.HolderLookup;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.Climate;
import net.minecraft.world.level.biome.MultiNoiseBiomeSourceParameterList;
import net.minecraft.world.level.levelgen.NoiseGeneratorSettings;
import net.minecraft.world.level.levelgen.RandomState;

// Writes the overworld biome golden used by terrain.
// Passing parameters-only as the second argument emits just the parameter list.
//
// biomepoint: every entry of the overworld parameter list, in list order.
// biometarget: the list's nearest entry for a quantized climate point.
// biomeat: the biome the seeded climate sampler picks at a quart position.
// biomechunk: a digest of the biome names of one chunk's quarts in the order
// ChunkAccess.fillBiomesFromNoise asks for them (a section at a time from the
// bottom, x, then y, then z), joined by newlines.
//
// The search starts from the thread's last result, which decides entries the
// target is equally near (the caves' overlaps), so each line is computed on a
// thread of its own: the search starts from nothing, and a chunk's queries
// follow one another.
public class OverworldBiomeGolden {
    static final long[] SEEDS = {0L, 12345L, -4172144997902289642L};
    static final int[][] CHUNKS = {{0, 0}, {-1, -1}, {3, -4}, {-4, 3}, {6, 1}, {60, 62}, {-70, 5}, {100, -100}, {-380, -378}, {25, -31}, {-12, 47}, {210, 40}, {1500, -900}, {-2400, 2600}};
    static final int MIN_QUART_Y = -16;
    static final int QUART_HEIGHT = 96;

    static <T> T onFreshThread(Callable<T> task) throws Exception {
        Object[] result = new Object[1];
        Throwable[] failure = new Throwable[1];
        Thread t = new Thread(() -> {
            try {
                result[0] = task.call();
            } catch (Throwable e) {
                failure[0] = e;
            }
        });
        t.start();
        t.join();
        if (failure[0] != null) {
            throw new Exception(failure[0]);
        }
        @SuppressWarnings("unchecked")
        T value = (T) result[0];
        return value;
    }

    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        PrintWriter out = new PrintWriter(args[0], "UTF-8");
        out.println("# Generated by tools/java/OverworldBiomeGolden.java from the vanilla " + WorldgenSupport.version() + " server jar. DO NOT EDIT.");

        HolderLookup.Provider lookup = WorldgenSupport.lookup();
        Map<MultiNoiseBiomeSourceParameterList.Preset, Climate.ParameterList<ResourceKey<Biome>>> presets = MultiNoiseBiomeSourceParameterList.knownPresets();
        Climate.ParameterList<ResourceKey<Biome>> list = presets.get(MultiNoiseBiomeSourceParameterList.Preset.OVERWORLD);

        for (var entry : list.values()) {
            Climate.ParameterPoint p = entry.getFirst();
            out.println("biomepoint " + range(p.temperature()) + " " + range(p.humidity()) + " " + range(p.continentalness())
                + " " + range(p.erosion()) + " " + range(p.depth()) + " " + range(p.weirdness()) + " " + p.offset() + " " + entry.getSecond().identifier().getPath());
        }

        if (args.length > 1 && args[1].equals("parameters-only")) {
            out.close();
            return;
        }

        // Targets over the whole climate space, and clustered on the parameter
        // thresholds, where the ranges touch.
        Random rng = new Random(2827);
        long[] edges = {-10000, -4500, -1500, 2000, 5500, -7800, -3750, -2225, 500, 4500, -1100, 300, 3000, -1900, 2000, 9000, 11000, 8000, -8500};
        int mismatches = 0;
        for (int i = 0; i < 3000; i++) {
            long[] v = new long[6];
            for (int d = 0; d < 6; d++) {
                if (i % 2 == 0) {
                    v[d] = rng.nextInt(20001) - 10000;
                } else {
                    v[d] = edges[rng.nextInt(edges.length)] + rng.nextInt(3) - 1;
                }
            }
            if (i % 4 >= 2) {
                v[4] = rng.nextInt(13001) - 1000;
            }
            Climate.TargetPoint t = new Climate.TargetPoint(v[0], v[1], v[2], v[3], v[4], v[5]);
            ResourceKey<Biome> found = onFreshThread(() -> list.findValue(t));
            if (found != list.findValueBruteForce(t)) {
                mismatches++;
            }
            out.println("biometarget " + v[0] + " " + v[1] + " " + v[2] + " " + v[3] + " " + v[4] + " " + v[5] + " " + found.identifier().getPath());
        }
        System.err.println("R-tree and brute force disagree on " + mismatches + " targets");

        for (long seed : SEEDS) {
            RandomState random = WorldgenSupport.randomState(lookup, NoiseGeneratorSettings.OVERWORLD, seed);
            Climate.Sampler sampler = WorldgenSupport.climateSampler(random);
            Random positions = new Random(seed ^ 2827);
            for (int i = 0; i < 400; i++) {
                int qx = positions.nextInt(40001) - 20000;
                int qz = positions.nextInt(40001) - 20000;
                if (i % 3 == 0) {
                    qx = positions.nextInt(257) - 128;
                    qz = positions.nextInt(257) - 128;
                }
                int qy = MIN_QUART_Y + positions.nextInt(QUART_HEIGHT);
                int qxf = qx, qyf = qy, qzf = qz;
                out.println("biomeat " + seed + " " + qx + " " + qy + " " + qz + " " + onFreshThread(() -> list.findValue(sampler.sample(qxf, qyf, qzf))).identifier().getPath());
            }
            for (int[] c : CHUNKS) {
                MessageDigest digest = MessageDigest.getInstance("SHA-256");
                Object resolver;
                Method at;
                if (WorldgenSupport.version().equals("26.3")) {
                    var source = MultiNoiseBiomeSource.createFromPreset(Holder.direct(new MultiNoiseBiomeSourceParameterList(
                        MultiNoiseBiomeSourceParameterList.Preset.OVERWORLD, lookup.lookupOrThrow(Registries.BIOME))));
                    resolver = source.getClass().getMethod("createResolverForChunk", Climate.Sampler.class,
                        int.class, int.class, int.class, int.class, int.class, int.class).invoke(source,
                        WorldgenSupport.cachedClimateSampler(random), c[0] * 4, MIN_QUART_Y, c[1] * 4, 4, QUART_HEIGHT, 4);
                    at = Class.forName("net.minecraft.world.level.biome.BiomeResolver").getMethod("getNoiseBiome", int.class, int.class, int.class);
                } else {
                    resolver = null;
                    at = null;
                }
                onFreshThread(() -> {
                    for (int section = 0; section < QUART_HEIGHT / 4; section++) {
                        for (int x = 0; x < 4; x++) {
                            for (int y = 0; y < 4; y++) {
                                for (int z = 0; z < 4; z++) {
                                    int qx = c[0] * 4 + x, qy = MIN_QUART_Y + section * 4 + y, qz = c[1] * 4 + z;
                                    String name;
                                    if (resolver == null) {
                                        name = list.findValue(sampler.sample(qx, qy, qz)).identifier().getPath();
                                    } else {
                                        @SuppressWarnings("unchecked") Holder<Biome> biome = (Holder<Biome>) at.invoke(resolver, qx, qy, qz);
                                        name = biome.unwrapKey().orElseThrow().identifier().getPath();
                                    }
                                    digest.update((name + "\n").getBytes(StandardCharsets.UTF_8));
                                }
                            }
                        }
                    }
                    return null;
                });
                out.println("biomechunk " + seed + " " + c[0] + " " + c[1] + " " + HexFormat.of().formatHex(digest.digest()));
            }
        }
        out.close();
    }

    static String range(Climate.Parameter p) {
        return p.min() + " " + p.max();
    }
}
