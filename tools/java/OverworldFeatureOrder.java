import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.IdentityHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import net.minecraft.SharedConstants;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.HolderSet;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.Climate;
import net.minecraft.world.level.biome.FeatureSorter;
import net.minecraft.world.level.biome.MultiNoiseBiomeSourceParameterList;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;

// Writes internal/server/world/levelgen/overworld_features.txt (mise run
// gen:overworld-features): the placed features of the overworld as
// FeatureSorter orders them, from the overworld biome source's possible biomes
// in the order ChunkGenerator builds its featuresPerStep from.
//
// biome: one line per possible biome, in order.
// feature: step, index within the step, name, and the biomes whose feature
// lists carry it (comma-separated names).
public class OverworldFeatureOrder {
    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        HolderLookup.Provider lookup = WorldgenSupport.lookup();
        var list = MultiNoiseBiomeSourceParameterList.knownPresets().get(MultiNoiseBiomeSourceParameterList.Preset.OVERWORLD);
        LinkedHashSet<ResourceKey<Biome>> keys = new LinkedHashSet<>();
        for (var entry : list.values()) {
            keys.add(entry.getSecond());
        }
        HolderLookup.RegistryLookup<Biome> biomes = lookup.lookupOrThrow(Registries.BIOME);
        List<Biome> sources = new ArrayList<>();
        for (ResourceKey<Biome> key : keys) {
            sources.add(biomes.getOrThrow(key).value());
        }
        List<FeatureSorter.StepFeatureData> steps = FeatureSorter.buildFeaturesPerStep(sources, b -> b.getGenerationSettings().features(), true);

        IdentityHashMap<PlacedFeature, String> names = new IdentityHashMap<>();
        lookup.lookupOrThrow(Registries.PLACED_FEATURE).listElements().forEach(h -> names.put(h.value(), h.key().identifier().toString()));

        PrintWriter out = new PrintWriter(args[0], "UTF-8");
        out.println("# Generated by tools/java/OverworldFeatureOrder.java from the vanilla " + WorldgenSupport.version() + " server jar. DO NOT EDIT.");
        for (ResourceKey<Biome> key : keys) {
            out.println("biome " + key.identifier().getPath());
        }
        for (int step = 0; step < steps.size(); step++) {
            List<PlacedFeature> features = steps.get(step).features();
            for (int i = 0; i < features.size(); i++) {
                PlacedFeature feature = features.get(i);
                List<String> carriers = new ArrayList<>();
                for (ResourceKey<Biome> key : keys) {
                    List<HolderSet<PlacedFeature>> perStep = biomes.getOrThrow(key).value().getGenerationSettings().features();
                    if (step < perStep.size() && perStep.get(step).stream().anyMatch(h -> h.value().equals(feature))) {
                        carriers.add(key.identifier().getPath());
                    }
                }
                String name = names.get(feature);
                if (name == null) {
                    name = "inline";
                }
                out.println("feature " + step + " " + i + " " + name + " " + String.join(",", carriers));
            }
        }
        out.close();
    }
}
