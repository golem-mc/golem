import java.io.PrintWriter;
import net.minecraft.SharedConstants;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.LevelHeightAccessor;
import net.minecraft.world.level.biome.Biomes;
import net.minecraft.world.level.biome.FixedBiomeSource;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.NoiseGeneratorSettings;

// column <dim> <seed> <x> <z> <minY> <height> -> <columnMinY>:<block*count,...>|null <surfaceHeight> <floorHeight>
// Base columns and heights call the generator's public API, with no material rule or structures.
public class ColumnGolden {
    static String name(BlockState s) {
        return BuiltInRegistries.BLOCK.getKey(s.getBlock()).getPath();
    }

    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        HolderLookup.Provider lookup = WorldgenSupport.lookup();
        try (var resources = WorldgenSupport.resources(); PrintWriter out = new PrintWriter(args[0], "UTF-8")) {
            // Heightmap predicates read BLOCKS_MOTION_IN_HEIGHTMAP, which bootstrap alone does not bind.
            WorldgenSupport.bindTags(resources);
            if (!Heightmap.Types.OCEAN_FLOOR_WG.isOpaque().test(Blocks.STONE.defaultBlockState())) {
                throw new IllegalStateException("heightmap block tag is unbound");
            }
            out.println("# Generated by tools/java/ColumnGolden.java from vanilla " + WorldgenSupport.version() + ". DO NOT EDIT.");
            int[][] positions = {{0,0}, {37,-91}, {-1234,567}, {160,160}, {-480,320}, {100003,250007}};
            int[][] ranges = {{-64,384}, {0,96}, {-96,512}, {320,16}, {-128,32}, {-33,113}};
            for (String dim : new String[]{"overworld", "nether", "end"}) {
                var key = dim.equals("nether") ? NoiseGeneratorSettings.NETHER : dim.equals("end") ? NoiseGeneratorSettings.END : NoiseGeneratorSettings.OVERWORLD;
                var settings = lookup.lookupOrThrow(Registries.NOISE_SETTINGS).getOrThrow(key);
                var biome = lookup.lookupOrThrow(Registries.BIOME).getOrThrow(Biomes.PLAINS);
                var generator = new NoiseBasedChunkGenerator(new FixedBiomeSource(biome), settings);
                for (long seed : new long[]{12345L, -4172144997902289642L}) {
                    var random = WorldgenSupport.randomState(lookup, key, seed);
                    for (int[] pos : positions) {
                        for (int[] range : ranges) {
                            var heights = LevelHeightAccessor.create(range[0], range[1]);
                            var column = generator.getBaseColumn(pos[0], pos[1], heights, random);
                            String text = "null";
                            if (column != null) {
                                int minY = Math.max(range[0], settings.value().noiseSettings().minY());
                                int topY = Math.min(range[0] + range[1], settings.value().noiseSettings().minY() + settings.value().noiseSettings().height());
                                StringBuilder runs = new StringBuilder();
                                String last = null;
                                int count = 0;
                                for (int y = minY; y < topY; y++) {
                                    String block = name(column.getBlock(y));
                                    if (block.equals(last)) { count++; continue; }
                                    if (last != null) { runs.append(last).append('*').append(count).append(','); }
                                    last = block;
                                    count = 1;
                                }
                                runs.append(last).append('*').append(count);
                                text = minY + ":" + runs;
                            }
                            out.println("column " + dim + " " + seed + " " + pos[0] + " " + pos[1] + " " + range[0] + " " + range[1] + " -> " + text
                                + " " + generator.getBaseHeight(pos[0], pos[1], Heightmap.Types.WORLD_SURFACE_WG, heights, random)
                                + " " + generator.getBaseHeight(pos[0], pos[1], Heightmap.Types.OCEAN_FLOOR_WG, heights, random));
                        }
                    }
                }
            }
        }
    }
}
