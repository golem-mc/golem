import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import java.io.PrintWriter;
import java.lang.reflect.Proxy;
import java.util.LinkedHashMap;
import net.minecraft.SharedConstants;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.RegistryOps;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.levelgen.LegacyRandomSource;
import net.minecraft.world.level.levelgen.WorldgenRandom;
import net.minecraft.world.level.levelgen.XoroshiroRandomSource;
import net.minecraft.world.level.levelgen.feature.stateproviders.BlockStateProvider;
import net.minecraft.world.level.levelgen.synth.NormalNoise;

// vanilla: BlockStateProvider.CODEC, NormalNoise.DIRECT_CODEC
public class StateProviderGolden {
    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        var resources = WorldgenSupport.resources();
        WorldgenSupport.bindTags(resources);
        var lookup = net.minecraft.core.HolderLookup.Provider.create(java.util.stream.Stream.concat(
            net.minecraft.core.RegistryAccess.fromRegistryOfRegistries(BuiltInRegistries.REGISTRY).listRegistries(),
            WorldgenSupport.loadWorld(resources).listRegistries()));
        var ops = RegistryOps.create(JsonOps.INSTANCE, lookup);
        var cases = new LinkedHashMap<String, String>();
        String[] registered = {"cave_vines_body", "cave_vines_head", "flower_flower_forest", "flower_meadow", "flower_plain", "mangrove_propagule", "podzol_beneath_tree", "soil_beneath_tree"};
        try (var out = new PrintWriter(args[0])) {
            out.println("# Generated by StateProviderGolden on " + SharedConstants.getCurrentVersion().name());
            for (String name : registered) {
                String path = "/data/minecraft/worldgen/block_state_provider/" + name + ".json";
                String doc;
                try (var in = StateProviderGolden.class.getResourceAsStream(path)) {
                    doc = JsonParser.parseString(new String(in.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8)).toString();
                }
                out.println("provider\t" + "minecraft:" + name + "\t" + doc);
                cases.put(name, "\"minecraft:" + name + "\"");
            }
            cases.put("direct", "{\"id\":\"minecraft:oak_log\",\"properties\":{\"axis\":\"x\"}}");
            cases.put("simple", "{\"type\":\"minecraft:simple\",\"state\":\"minecraft:stone\"}");
            cases.put("rotated", "{\"type\":\"minecraft:rotated\",\"state\":{\"type\":\"minecraft:weighted\",\"entries\":[{\"data\":\"minecraft:oak_log\",\"weight\":2},{\"data\":\"minecraft:furnace\",\"weight\":3}]}}");
            cases.put("fixed_rotation", "{\"type\":\"minecraft:rotated\",\"state\":{\"id\":\"minecraft:oak_stairs\",\"properties\":{\"half\":\"top\"}},\"direction\":\"east\"}");
            cases.put("vertical_rotation", "{\"type\":\"minecraft:rotated\",\"state\":{\"id\":\"minecraft:oak_stairs\",\"properties\":{\"facing\":\"east\"}},\"direction\":\"up\"}");
            cases.put("copy", "{\"type\":\"minecraft:copy_properties\",\"source\":{\"id\":\"minecraft:oak_stairs\",\"properties\":{\"half\":\"top\"}}}");
            cases.put("copy_different_domain", "{\"type\":\"minecraft:copy_properties\",\"source\":{\"id\":\"minecraft:dispenser\",\"properties\":{\"facing\":\"east\",\"triggered\":\"true\"}}}");
            cases.put("copy_unshared", "{\"type\":\"minecraft:copy_properties\",\"source\":{\"id\":\"minecraft:oak_log\",\"properties\":{\"axis\":\"x\"}}}");
            cases.put("random", "{\"type\":\"minecraft:random_block\",\"blocks\":[\"minecraft:stone\",\"minecraft:dirt\",\"minecraft:grass_block\"]}");
            cases.put("random_tag", "{\"type\":\"minecraft:random_block\",\"blocks\":\"#minecraft:anvil\"}");
            cases.put("empty", "{\"type\":\"minecraft:random_block\",\"blocks\":[]}");
            cases.put("rule_continue", "{\"type\":\"minecraft:rule_based\",\"rules\":[{\"if_true\":{\"type\":\"minecraft:true\"},\"then\":{\"type\":\"minecraft:random_block\",\"blocks\":[]}},{\"if_true\":{\"type\":\"minecraft:true\"},\"then\":{\"id\":\"minecraft:gold_block\"}}]}");
            cases.put("rule_fallback", "{\"type\":\"minecraft:rule_based\",\"rules\":[],\"fallback\":\"minecraft:soil_beneath_tree\"}");
            cases.put("randomized_positive", "{\"type\":\"minecraft:randomized_int\",\"property\":\"pickles\",\"source\":{\"id\":\"minecraft:sea_pickle\"},\"values\":{\"type\":\"minecraft:uniform\",\"min_inclusive\":1,\"max_inclusive\":4}}");
            cases.put("randomized_missing", "{\"type\":\"minecraft:randomized_int\",\"property\":\"unknown\",\"source\":{\"id\":\"minecraft:stone\"},\"values\":2}");
            cases.put("no_rule", "{\"type\":\"minecraft:rule_based\",\"rules\":[]}");
            BlockState current = Blocks.OAK_STAIRS.defaultBlockState().setValue(net.minecraft.world.level.block.state.properties.BlockStateProperties.HORIZONTAL_FACING, net.minecraft.core.Direction.WEST);
            LevelAccessor level = (LevelAccessor) Proxy.newProxyInstance(StateProviderGolden.class.getClassLoader(), new Class<?>[]{LevelAccessor.class}, (proxy, method, values) -> {
                if (method.getName().equals("getBlockState")) return current;
                throw new UnsupportedOperationException(method.getName());
            });
            int[][] points = {{0, 64, 0}, {-12345, -32, 6789}, {16777217, 100, -16777219}, {314, 85, -234}, {-34, 12, 912}};
            for (var entry : cases.entrySet()) {
                out.println("case\t" + entry.getKey() + "\t" + entry.getValue());
                var provider = BlockStateProvider.CODEC.parse(ops, JsonParser.parseString(entry.getValue())).getOrThrow().value();
                for (long seed : new long[]{0, 12345, -413}) {
                    var random = new WorldgenRandom(new XoroshiroRandomSource(seed));
                    for (int[] p : points) {
                        var state = provider.getOptionalState(level, random, new BlockPos(p[0], p[1], p[2]));
                        String encoded = state == null ? "null" : BlockState.CODEC.encodeStart(JsonOps.INSTANCE, state).getOrThrow().toString();
                        out.printf("sample\t%s\t%d\t%d\t%d\t%d\t%s\t%d%n", entry.getKey(), seed, p[0], p[1], p[2], encoded, random.nextInt());
                    }
                }
            }
            for (String normalize : new String[]{"true", "false", "\"legacy\""}) {
                String doc = "{\"base_octave\":-5,\"base_amplitude\":0.7,\"octave_count\":4,\"amplitude_modifiers\":[1,0,0.5,2],\"normalize\":" + normalize + "}";
                var noise = NormalNoise.DIRECT_CODEC.parse(JsonOps.INSTANCE, JsonParser.parseString(doc)).getOrThrow().create(new WorldgenRandom(new LegacyRandomSource(2345)));
                for (int[] p : points) out.printf("noise\t%s\t%d\t%d\t%d\t%08x%n", doc, p[0], p[1], p[2], Float.floatToRawIntBits(noise.get(p[0], p[1], p[2])));
            }
        }
    }
}
