// Only world reads/writes are mocked; placement, rotation, chest reorientation,
// loot random draws and saved flags all run through vanilla's own classes.
public class SmallPortsGolden {
    static int height(int mode, int x, int z) { return 65 + (mode == 0 ? 0 : Math.floorMod(x * 3 + z * 5, 7)); }
    static BlockState terrain(int mode, BlockPos p) {
        if (p.getY() < height(mode, p.getX(), p.getZ())) return Blocks.STONE.defaultBlockState();
        return Blocks.AIR.defaultBlockState();
    }
    static void number(MessageDigest digest, int value) {
        digest.update((byte)(value >> 24)); digest.update((byte)(value >> 16));
        digest.update((byte)(value >> 8)); digest.update((byte)value);
    }
    public static void main(String[] args) throws Exception {
        try { generate(args); } catch (Throwable e) { e.printStackTrace(new java.io.PrintStream(new java.io.FileOutputStream(java.io.FileDescriptor.err))); System.exit(1); }
    }
    static void generate(String[] args) throws Exception {
        SharedConstants.tryDetectVersion(); Bootstrap.bootStrap();
        Direction[] directions = {Direction.NORTH, Direction.EAST, Direction.SOUTH, Direction.WEST};
        try (var resources = WorldgenSupport.resources();
             var storage = net.minecraft.world.level.storage.LevelStorageSource.createDefault(java.nio.file.Path.of("smallports-golden-worlds")).createAccess("test");
             PrintWriter out = new PrintWriter(args[0], StandardCharsets.UTF_8)) {
            WorldgenSupport.bindTags(resources);
            var manager = new net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplateManager(resources,storage,net.minecraft.util.datafix.DataFixers.getDataFixer(),net.minecraft.core.registries.BuiltInRegistries.BLOCK);
            out.println("# Vanilla " + WorldgenSupport.version() + " small structure ports; generated by SmallPortsGolden.java. Shape updates and mob finalization excluded.");
            for (String kind : new String[]{"pyramid","hut","top","middle","bottom"}) for (long seed : new long[]{0, 12345}) for (int mode = 0; mode < 2; mode++) for (int dir = 0; dir < 4; dir++) for (int reverse = 0; reverse < 2; reverse++) {
                final int terrainMode = mode;
                net.minecraft.world.level.levelgen.structure.StructurePiece piece;
                if (kind.equals("pyramid") || kind.equals("hut")) {
                    piece = kind.equals("pyramid") ? new net.minecraft.world.level.levelgen.structure.structures.DesertPyramidPiece(new LegacyRandomSource(seed),-3,7) : new net.minecraft.world.level.levelgen.structure.structures.SwampHutPiece(new LegacyRandomSource(seed),-3,7);
                    piece.setOrientation(directions[dir]);
                    int w = kind.equals("pyramid") ? 21 : ((dir&1)==0 ? 7 : 9), d = kind.equals("pyramid") ? 21 : ((dir&1)==0 ? 9 : 7);
                    var f = net.minecraft.world.level.levelgen.structure.StructurePiece.class.getDeclaredField("boundingBox"); f.setAccessible(true);
                    f.set(piece,new BoundingBox(-3,64,7,-3+w-1,kind.equals("pyramid")?78:70,7+d-1));
                    if (kind.equals("hut")) for (String flag : new String[]{"spawnedWitch","spawnedCat"}) { var f2=piece.getClass().getDeclaredField(flag); f2.setAccessible(true); f2.setBoolean(piece,true); }
                } else {
                    var igloo = new net.minecraft.world.level.levelgen.structure.structures.IglooPieces.IglooPiece(manager,Identifier.withDefaultNamespace("igloo/"+kind),new BlockPos(-3,90,7),net.minecraft.world.level.block.Rotation.values()[dir],kind.equals("top")?0:12);
                    igloo.placeSettings().setIgnoreEntities(true).setKnownShape(true);
                    piece=igloo;
                }
                Map<BlockPos, BlockState> blocks = new HashMap<>();
                Map<BlockPos, BlockEntity> entities = new HashMap<>();
                final long worldSeed = seed;
                final var regionRandom = new XoroshiroRandomSource(seed).forkPositional().fromHashOf(Identifier.withDefaultNamespace("worldgen_region_random")).forkPositional();
                final net.minecraft.util.RandomSource[] region = new net.minecraft.util.RandomSource[1];
                WorldGenLevel level = (WorldGenLevel) Proxy.newProxyInstance(SmallPortsGolden.class.getClassLoader(), new Class<?>[]{WorldGenLevel.class}, (proxy, method, a) -> {
                    switch (method.getName()) {
                        case "getChunk": return OverworldTreeGolden.chunk();
                        case "getSeed": return worldSeed;
                        case "getRandom": return region[0];
                        case "getMinY": return -64;
                        case "getHeight": return height(terrainMode,(int)a[1],(int)a[2]);
                        case "getMaxY": return 319;
                        case "registryAccess": return net.minecraft.core.RegistryAccess.fromRegistryOfRegistries(net.minecraft.core.registries.BuiltInRegistries.REGISTRY);
                        case "getBlockState": return blocks.getOrDefault((BlockPos)a[0], terrain(terrainMode, (BlockPos)a[0]));
                        case "getFluidState": return blocks.getOrDefault((BlockPos)a[0], terrain(terrainMode, (BlockPos)a[0])).getFluidState();
                        case "getBlockEntity": return a.length == 1 ? entities.get((BlockPos)a[0]) : java.util.Optional.ofNullable(entities.get((BlockPos)a[0]));
                        case "getHeightmapPos": {
                            BlockPos p = (BlockPos)a[1]; return new BlockPos(p.getX(), height(terrainMode, p.getX(), p.getZ()), p.getZ());
                        }
                        case "setBlock": {
                            BlockPos p = ((BlockPos)a[0]).immutable(); BlockState state = (BlockState)a[1]; blocks.put(p, state);
                            if (state.is(Blocks.CHEST)) entities.put(p, new ChestBlockEntity(p, state));
                            else if (state.is(Blocks.DISPENSER)) entities.put(p, new DispenserBlockEntity(p, state));
                            else if (state.is(Blocks.SUSPICIOUS_SAND)) entities.put(p,new net.minecraft.world.level.block.entity.BrushableBlockEntity(p,state));
                            else entities.remove(p);
                            return true;
                        }
                        default:
                            if (method.isDefault()) return InvocationHandler.invokeDefault(proxy, method, a);
                            throw new UnsupportedOperationException(method.getName());
                    }
                });
                MessageDigest draws = MessageDigest.getInstance("SHA-256");
                for (int i = 0; i < 6; i++) {
                    int index = reverse == 0 ? i : 5-i, cx = index % 3 - 1, cz = index / 3;
                    region[0] = regionRandom.at(cx*16,0,cz*16);
                    var rng = new WorldgenRandom(new XoroshiroRandomSource(seed + cx*31 + cz*17));
                    piece.postProcess(level, null, null, rng, new BoundingBox(cx*16,-64,cz*16,cx*16+15,319,cz*16+15), new ChunkPos(cx,cz), BlockPos.ZERO);
                    if (kind.equals("pyramid")) new net.minecraft.world.level.levelgen.structure.structures.DesertPyramidStructure(new net.minecraft.world.level.levelgen.structure.Structure.StructureSettings(net.minecraft.core.HolderSet.direct(),java.util.Map.of(),net.minecraft.world.level.levelgen.GenerationStep.Decoration.SURFACE_STRUCTURES,net.minecraft.world.level.levelgen.structure.TerrainAdjustment.NONE)).afterPlace(level,null,null,rng,new BoundingBox(cx*16,-64,cz*16,cx*16+15,319,cz*16+15),new ChunkPos(cx,cz),new net.minecraft.world.level.levelgen.structure.pieces.PiecesContainer(java.util.List.of(piece)));
                    number(draws, rng.nextInt());
                    if(kind.equals("pyramid")) number(draws,region[0].nextInt());
                }
                MessageDigest states = MessageDigest.getInstance("SHA-256"), loot = MessageDigest.getInstance("SHA-256");
                int count = 0;
                for (int x = -16; x < 32; x++) for (int y = 32; y < 88; y++) for (int z = 0; z < 32; z++) {
                    var p = new BlockPos(x,y,z); states.update(WorldgenSupport.stateBytes(blocks.getOrDefault(p, terrain(mode,p))));
                    if (entities.get(p) instanceof RandomizableContainerBlockEntity be) {
                        count++;
                        loot.update((x+","+y+","+z+":"+be.getLootTable().identifier()+":"+be.getLootTableSeed()+"\n").getBytes(StandardCharsets.UTF_8));
                    }
                }
                var tag = piece.createTag(null);
                out.printf("place %s %d %d %d %d %s %s %d %s%n",kind,seed,mode,dir,reverse,HexFormat.of().formatHex(states.digest()),HexFormat.of().formatHex(draws.digest()),count,HexFormat.of().formatHex(loot.digest()));
                out.println(tag);

            }
            starts(out,manager);
        }
    }
    static void starts(PrintWriter out,net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplateManager manager) throws Exception {
        RegistryAccess lookup;
        try (var resources = WorldgenSupport.resources()) {
            WorldgenSupport.bindTags(resources);
            lookup = (RegistryAccess) WorldgenSupport.loadWorld(resources);
        }
        var biomes = MultiNoiseBiomeSource.createFromPreset(lookup.lookupOrThrow(Registries.MULTI_NOISE_BIOME_SOURCE_PARAMETER_LIST).getOrThrow(MultiNoiseBiomeSourceParameterLists.OVERWORLD));
        var generator = new NoiseBasedChunkGenerator(biomes, lookup.lookupOrThrow(Registries.NOISE_SETTINGS).getOrThrow(NoiseGeneratorSettings.OVERWORLD));
        for (String kind : new String[]{"desert_pyramid","swamp_hut","igloo"}) {
        var temple = lookup.lookupOrThrow(Registries.STRUCTURE).getOrThrow(ResourceKey.create(Registries.STRUCTURE, Identifier.withDefaultNamespace(kind))).value();
        var set = lookup.lookupOrThrow(Registries.STRUCTURE_SET).getOrThrow(ResourceKey.create(Registries.STRUCTURE_SET, Identifier.withDefaultNamespace(kind.equals("desert_pyramid")?"desert_pyramids":kind.equals("swamp_hut")?"swamp_huts":"igloos"))).value();
        var placement = (RandomSpreadStructurePlacement)set.placement();
        for (long seed : new long[]{0,12345}) {
            var random = WorldgenSupport.randomState(lookup, NoiseGeneratorSettings.OVERWORLD, seed);
            int found=0;
            for (int x = -12; x <= 12; x++) for (int z = -12; z <= 12; z++) {
                if ((x < -3 || x > 3 || z < -3 || z > 3) && found>=2) continue;
                var chunk = placement.getPotentialStructureChunk(seed, x*32, z*32);
                var context = WorldgenSupport.structureContext(lookup,generator,biomes,random,manager,seed,chunk,LevelHeightAccessor.create(-64,384),temple.biomes()::contains);
                var stub = temple.findValidGenerationPoint(context);
                if (stub.isEmpty()) { if(x>=-3 && x<=3 && z>=-3 && z<=3) out.printf("start %s %d %d %d absent%n",kind,seed,chunk.x(),chunk.z()); continue; }
                found++;
                var pieces = stub.get().getPiecesBuilder().build().pieces();
                out.printf("start %s %d %d %d present %d%n",kind,seed,chunk.x(),chunk.z(),pieces.size());
                for (var piece:pieces) out.println(piece.createTag(null));
            }
        }
        }
    }
}
