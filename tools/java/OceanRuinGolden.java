// Pins the jar's assembly and complete processor pipeline, including archaeology.
public class OceanRuinGolden {
    static <T> void bindTags(net.minecraft.server.packs.resources.ResourceManager resources, net.minecraft.core.Registry<T> registry, ResourceKey<? extends net.minecraft.core.Registry<T>> key) {
        @SuppressWarnings({"unchecked", "rawtypes"})
        var tags = (java.util.Map<net.minecraft.tags.TagKey<T>, List<net.minecraft.core.Holder<T>>>) net.minecraft.tags.TagLoader.loadTagsForRegistry(resources, (ResourceKey) key, (net.minecraft.tags.TagLoader.ElementLookup) net.minecraft.tags.TagLoader.ElementLookup.fromFrozenRegistry(registry));
        registry.prepareTagReload(new net.minecraft.tags.TagLoader.LoadResult<>(key, tags)).apply();
    }

    public static void main(String[] args) throws Exception {
        try { generate(args); } catch (Throwable e) {
            e.printStackTrace(new java.io.PrintStream(new java.io.FileOutputStream(java.io.FileDescriptor.err)));
            System.exit(1);
        }
    }
    static void generate(String[] args) throws Exception {
        SharedConstants.tryDetectVersion(); Bootstrap.bootStrap();
        var lookup = WorldgenSupport.lookup();
        var access = RegistryAccess.fromRegistryOfRegistries(BuiltInRegistries.REGISTRY);
        var biomes = MultiNoiseBiomeSource.createFromPreset(lookup.lookupOrThrow(Registries.MULTI_NOISE_BIOME_SOURCE_PARAMETER_LIST).getOrThrow(MultiNoiseBiomeSourceParameterLists.OVERWORLD));
        var generator = new NoiseBasedChunkGenerator(biomes, lookup.lookupOrThrow(Registries.NOISE_SETTINGS).getOrThrow(NoiseGeneratorSettings.OVERWORLD));
        try (var resources = WorldgenSupport.resources();
             var storage = LevelStorageSource.createDefault(Path.of("oceanruin-golden-worlds")).createAccess("test");
             var out = new PrintWriter(args[0], "UTF-8")) {
            bindTags(resources, BuiltInRegistries.BLOCK, Registries.BLOCK);
            var manager = new StructureTemplateManager(resources, storage, DataFixers.getDataFixer(), BuiltInRegistries.BLOCK);
            var serialization = new StructurePieceSerializationContext(resources, access, manager);
            out.println("# Generated by OceanRuinGolden.java from vanilla " + WorldgenSupport.version() + ". DO NOT EDIT.");
            for (long seed : new long[]{0L,12345L}) {
                var random = WorldgenSupport.randomState(lookup, NoiseGeneratorSettings.OVERWORLD, seed);
                for (String id : new String[]{"ocean_ruin_cold","ocean_ruin_warm"}) {
                    var structure = (net.minecraft.world.level.levelgen.structure.structures.OceanRuinStructure)lookup.lookupOrThrow(Registries.STRUCTURE).getOrThrow(ResourceKey.create(Registries.STRUCTURE,Identifier.withDefaultNamespace(id))).value();
                    for (int i=0;i<32;i++) {
                        int x=i*7-100,z=i*3-50;
                        var ctx = WorldgenSupport.structureContext(access,generator,biomes,random,manager,seed,new ChunkPos(x,z),LevelHeightAccessor.create(-64,384), b -> true);
                        var pieces = structure.findGenerationPoint(ctx).orElseThrow().getPiecesBuilder().build().pieces();
                        out.printf("start %d %d %d %s %d%n",seed,x,z,id,pieces.size());
                        for (var p:pieces) out.println(p.createTag(serialization));
                    }
                }
                processors(out,manager,seed);
            }
        }
    }
    static void processors(PrintWriter out,StructureTemplateManager manager,long seed) throws Exception {
        var uf = sun.misc.Unsafe.class.getDeclaredField("theUnsafe"); uf.setAccessible(true);
        var unsafe = (sun.misc.Unsafe)uf.get(null);
        var server = (net.minecraft.server.MinecraftServer)unsafe.allocateInstance(net.minecraft.server.dedicated.DedicatedServer.class);
        var sf = net.minecraft.server.MinecraftServer.class.getDeclaredField("worldGenSettings"); sf.setAccessible(true);
        sf.set(server,new net.minecraft.world.level.levelgen.WorldGenSettings(new net.minecraft.world.level.levelgen.WorldOptions(seed,true,false),null));
        var level = (net.minecraft.server.level.ServerLevel)unsafe.allocateInstance(net.minecraft.server.level.ServerLevel.class);
        var lf = net.minecraft.server.level.ServerLevel.class.getDeclaredField("server"); lf.setAccessible(true); lf.set(level,server);
        var world = (net.minecraft.world.level.ServerLevelAccessor)java.lang.reflect.Proxy.newProxyInstance(OceanRuinGolden.class.getClassLoader(),new Class[]{net.minecraft.world.level.ServerLevelAccessor.class},(proxy,method,a) -> {
            if (method.getName().equals("getLevel")) return level;
            if (method.getName().equals("getBlockState")) return net.minecraft.world.level.block.Blocks.WATER.defaultBlockState();
            throw new UnsupportedOperationException(method.toString());
        });
        var palettes = net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplate.class.getDeclaredField("palettes"); palettes.setAccessible(true);
        var settingsMethod = net.minecraft.world.level.levelgen.structure.structures.OceanRuinPieces.OceanRuinPiece.class.getDeclaredMethod("makeSettings",net.minecraft.world.level.block.Rotation.class,float.class,net.minecraft.world.level.levelgen.structure.structures.OceanRuinStructure.Type.class); settingsMethod.setAccessible(true);
        for (String kind:new String[]{"warm","brick","cracked","mossy"}) for (boolean big:new boolean[]{false,true}) {
            int[] nums = big ? (kind.equals("warm") ? new int[]{4,5,6,7} : new int[]{1,2,3,8}) : new int[]{1,2,3,4,5,6,7,8};
            for (int n:nums) for (var rot:net.minecraft.world.level.block.Rotation.values()) {
                String name=(big?"big_":"")+kind+"_"+n;
                float integrity=kind.equals("cracked")?0.7f:kind.equals("mossy")?0.5f:big?0.9f:0.8f;
                var t=manager.getOrCreate(Identifier.withDefaultNamespace("underwater_ruin/"+name));
                var settings=(net.minecraft.world.level.levelgen.structure.templatesystem.StructurePlaceSettings)settingsMethod.invoke(null,rot,integrity,kind.equals("warm")?net.minecraft.world.level.levelgen.structure.structures.OceanRuinStructure.Type.WARM:net.minecraft.world.level.levelgen.structure.structures.OceanRuinStructure.Type.COLD);
                var pos=new net.minecraft.core.BlockPos(-17,41,13);
                var palette=((List<net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplate.Palette>)palettes.get(t)).getFirst();
                var processed=net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplate.processBlockInfos(world,pos,pos,settings,palette.blocks());
                var bytes=new java.io.ByteArrayOutputStream(); var data=new java.io.DataOutputStream(bytes);
                for (var b:processed) {
                    data.writeInt(b.pos().getX());data.writeInt(b.pos().getY());data.writeInt(b.pos().getZ());
                    data.write(WorldgenSupport.stateBytes(b.state().rotate(rot)));
                    data.writeLong(b.nbt()==null?0:b.nbt().getLongOr("LootTableSeed",0L));
                }
                out.printf("process %d %s %d %d %s%n",seed,name,rot.ordinal(),processed.size(),java.util.HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(bytes.toByteArray())));
            }
        }
    }
}
