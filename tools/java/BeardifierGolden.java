import java.io.PrintWriter;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import net.minecraft.SharedConstants;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.levelgen.Beardifier;
import net.minecraft.world.level.levelgen.densityfunction.DensityBuffer;
import net.minecraft.world.level.levelgen.densityfunction.DensityVolume;
import net.minecraft.world.level.levelgen.densityfunction.SamplerContext;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.level.levelgen.structure.TerrainAdjustment;
import net.minecraft.world.level.levelgen.structure.pools.JigsawJunction;
import net.minecraft.world.level.levelgen.structure.pools.StructureTemplatePool;

// Records the beardifier kernel and complete point ranges as SHA-256 of
// eight-digit Float.floatToRawIntBits hex lines, without a trailing newline.
// beard: case, range, digest, rigid boxes/adjustments/deltas and junctions.
// beardvolume: case, sizes, origin, steps, then raw float bits in buffer order.
public class BeardifierGolden {
    static String digest(List<String> lines) throws Exception {
        MessageDigest md = MessageDigest.getInstance("SHA-256");
        md.update(String.join("\n", lines).getBytes(StandardCharsets.UTF_8));
        return HexFormat.of().formatHex(md.digest());
    }

    static String floatBits(float value) {
        return HexFormat.of().toHexDigits(Float.floatToRawIntBits(value));
    }

    record Case(List<Beardifier.Rigid> rigids, List<int[]> junctions, BoundingBox range) {}

    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        PrintWriter out = new PrintWriter(args[0], "UTF-8");
        out.println("# Generated by tools/java/BeardifierGolden.java from the vanilla " + WorldgenSupport.version() + " server jar. DO NOT EDIT.");
        out.println("# kernel and beard hash eight-digit float-bit hex lines, with no trailing newline.");
        out.println("# beardvolume lists float-bit hex in DensityVolume buffer order (y innermost).");
        Field kernelField = Beardifier.class.getDeclaredField("BEARD_KERNEL");
        kernelField.setAccessible(true);
        float[] kernel = (float[]) kernelField.get(null);
        List<String> kernelLines = new ArrayList<>();
        for (float f : kernel) {
            kernelLines.add(floatBits(f));
        }
        out.println("kernel " + kernel.length + " " + digest(kernelLines));

        // Each adaptation alone, with a ground delta, junctions alone, and a
        // mix where pieces of several adaptations overlap.
        List<Case> cases = new ArrayList<>();
        BoundingBox box = new BoundingBox(10, 60, -5, 25, 70, 8);
        BoundingBox range = new BoundingBox(-20, 30, -35, 55, 100, 38);
        for (TerrainAdjustment a : TerrainAdjustment.values()) {
            cases.add(new Case(List.of(new Beardifier.Rigid(box, a, 0)), List.of(), range));
        }
        cases.add(new Case(List.of(new Beardifier.Rigid(box, TerrainAdjustment.BEARD_THIN, 3)), List.of(), range));
        cases.add(new Case(List.of(new Beardifier.Rigid(box, TerrainAdjustment.BEARD_BOX, 4)), List.of(), range));
        // Ground above the box: only the 24-block margin reaches it.
        cases.add(new Case(List.of(new Beardifier.Rigid(box, TerrainAdjustment.BEARD_THIN, 22)), List.of(), range));
        cases.add(new Case(List.of(), List.of(new int[] {0, 64, 0, 2}, new int[] {7, 61, -3, -1}), new BoundingBox(-20, 40, -20, 20, 90, 20)));
        cases.add(new Case(List.of(
            new Beardifier.Rigid(new BoundingBox(-8, 62, -8, 8, 75, 8), TerrainAdjustment.BEARD_THIN, 1),
            new Beardifier.Rigid(new BoundingBox(4, -20, 2, 30, 10, 21), TerrainAdjustment.BURY, 0),
            new Beardifier.Rigid(new BoundingBox(-30, 20, -15, -12, 40, 5), TerrainAdjustment.ENCAPSULATE, 0)),
            List.of(new int[] {-3, 63, 9, 1}), new BoundingBox(-50, -40, -40, 45, 100, 40)));
        for (int i = 0; i < cases.size(); i++) {
            Case c = cases.get(i);
            List<JigsawJunction> junctions = new ArrayList<>();
            BoundingBox all = null;
            StringBuilder desc = new StringBuilder();
            for (var r : c.rigids()) {
                BoundingBox b = r.box();
                all = all == null ? b : BoundingBox.encapsulating(all, b);
                desc.append(" rigid ").append(b.minX()).append(' ').append(b.minY()).append(' ').append(b.minZ()).append(' ')
                    .append(b.maxX()).append(' ').append(b.maxY()).append(' ').append(b.maxZ()).append(' ')
                    .append(r.terrainAdjustment().getSerializedName()).append(' ').append(r.groundLevelDelta());
            }
            for (int[] j : c.junctions()) {
                junctions.add(new JigsawJunction(j[0], j[1], j[2], j[3], StructureTemplatePool.Projection.RIGID));
                BoundingBox b = new BoundingBox(j[0], j[1], j[2], j[0], j[1], j[2]);
                all = all == null ? b : BoundingBox.encapsulating(all, b);
                desc.append(" junction ").append(j[0]).append(' ').append(j[1]).append(' ').append(j[2]);
            }
            Beardifier beard = new Beardifier(c.rigids(), junctions, all.inflatedBy(24));
            BoundingBox r = c.range();
            List<String> values = new ArrayList<>();
            for (int x = r.minX(); x <= r.maxX(); x++) {
                for (int y = r.minY(); y <= r.maxY(); y++) {
                    for (int z = r.minZ(); z <= r.maxZ(); z++) {
                        values.add(floatBits(beard.sampleValue(SamplerContext.EMPTY_UNCACHED, x, y, z)));
                    }
                }
            }
            out.println("beard " + i + " range " + r.minX() + " " + r.minY() + " " + r.minZ() + " " + r.maxX() + " " + r.maxY() + " " + r.maxZ()
                + " " + digest(values) + desc);
            // Include volumes crossing the affected box, non-unit strides and an empty intersection.
            int[][] volumes = {{11, 17, 13, -30, 24, -40, 8, 5, 7}, {9, 13, 7, -15, 39, -20, 3, 4, 5},
                {3, 5, 4, 1000, 200, -1000, 1, 1, 1}};
            for (int[] v : volumes) {
                DensityVolume volume = new DensityVolume(v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7], v[8]);
                DensityBuffer buffer = DensityBuffer.createUnpooled(volume.size());
                buffer.fill(Float.NaN);
                beard.sampleVolume(SamplerContext.EMPTY_UNCACHED, buffer, volume);
                StringBuilder line = new StringBuilder("beardvolume " + i);
                for (int value : v) line.append(' ').append(value);
                for (int index = 0; index < volume.size(); index++) line.append(' ').append(floatBits(buffer.get(index)));
                out.println(line);
            }
        }
        out.close();
    }
}
