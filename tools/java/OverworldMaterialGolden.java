import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import net.minecraft.SharedConstants;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.chunk.ProtoChunk;
import net.minecraft.world.level.chunk.UpgradeData;
import net.minecraft.world.level.levelgen.Aquifer;
import net.minecraft.world.level.levelgen.Beardifier;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.NoiseChunk;
import net.minecraft.world.level.levelgen.NoiseGeneratorSettings;
import net.minecraft.world.level.levelgen.WorldGenerationContext;
import net.minecraft.world.level.levelgen.blending.Blender;
import net.minecraft.world.level.levelgen.densityfunction.DensityVolume;

// Records MaterialSystem.buildSurface on the fixed synthetic columns in args[1].
// surfacechunk/column retain the complete chunk digest and three diagnostic columns.
// surfacemelt records Biome.shouldMeltFrozenOceanIcebergSlightly, z then x.
public class OverworldMaterialGolden {
    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        try (var resources = WorldgenSupport.resources()) {
            WorldgenSupport.bindTags(resources);
            TerrainGolden.lookup = WorldgenSupport.lookup();
        }
        try (PrintWriter out = new PrintWriter(args[0], "UTF-8")) {
            out.println("# Generated by tools/java/OverworldMaterialGolden.java from the vanilla " + WorldgenSupport.version() + " server jar. DO NOT EDIT.");
            long previousSeed = Long.MIN_VALUE;
            OverworldTerrainGolden.NaturalBiomes biomes = null;
            for (String line : Files.readAllLines(Path.of(args[1]))) {
                if (line.isBlank() || line.startsWith("#")) continue;
                String[] fields = line.split(" ");
                long seed = Long.parseLong(fields[0]);
                if (biomes == null || seed != previousSeed) {
                    biomes = new OverworldTerrainGolden.NaturalBiomes(seed);
                    previousSeed = seed;
                }
                int cx = Integer.parseInt(fields[1]), cz = Integer.parseInt(fields[2]);
                int level = Integer.parseInt(fields[3]), slope = Integer.parseInt(fields[4]);
                record(out, biomes, seed, cx, cz, level, slope, fields[5]);
            }
        }
    }

    static void record(PrintWriter out, OverworldTerrainGolden.NaturalBiomes biomes, long seed,
            int cx, int cz, int level, int slope, String label) throws Exception {
        var holder = TerrainGolden.lookup.lookupOrThrow(Registries.NOISE_SETTINGS).getOrThrow(NoiseGeneratorSettings.OVERWORLD);
        var settings = holder.value();
        var generator = new NoiseBasedChunkGenerator(biomes.source, holder);
        var chunk = new ProtoChunk(new ChunkPos(cx, cz), UpgradeData.EMPTY, biomes.heights, biomes.containers, null);
        chunk.getOrCreateHeightmapUnprimed(Heightmap.Types.WORLD_SURFACE_WG);
        var pos = new BlockPos.MutableBlockPos();
        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                int bx = cx * 16 + x, bz = cz * 16 + z;
                int height = MaterialGolden.height(level, slope, bx, bz);
                for (int y = -64; y <= Math.max(height, 62); y++) {
                    chunk.setBlockState(pos.set(bx, y, bz), (y <= height ? Blocks.STONE : Blocks.WATER).defaultBlockState());
                }
            }
        }
        var volume = new DensityVolume(16, 384, 16, cx * 16, -64, cz * 16);
        var sea = new Aquifer.FluidStatus(63, Blocks.WATER.defaultBlockState());
        var noise = new NoiseChunk(biomes.random, Beardifier.EMPTY, settings, (x, y, z) -> sea, Blender.empty(), volume);
        biomes.random.surfaceSystem().buildSurface(biomes.random, biomes.manager, new WorldGenerationContext(generator, biomes.heights),
            chunk, noise, settings.materialRule().value(), null);
        String prefix = seed + " " + cx + " " + cz + " " + level + " " + slope;
        var digest = MessageDigest.getInstance("SHA-256");
        var columns = new ArrayList<String>();
        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                StringBuilder rle = new StringBuilder();
                String last = null;
                int run = 0;
                for (int y = -64; y < 320; y++) {
                    String name = BuiltInRegistries.BLOCK.getKey(chunk.getBlockState(pos.set(cx * 16 + x, y, cz * 16 + z)).getBlock()).getPath();
                    digest.update((name + "\n").getBytes(StandardCharsets.UTF_8));
                    if (name.equals(last)) { run++; continue; }
                    if (last != null) rle.append(last).append('*').append(run).append(',');
                    last = name;
                    run = 1;
                }
                rle.append(last).append('*').append(run);
                if ((x == 0 && z == 0) || (x == 7 && z == 9) || (x == 15 && z == 15)) {
                    columns.add("surfacecolumn " + prefix + " " + x + " " + z + " " + rle);
                }
            }
        }
        out.println("surfacechunk " + prefix + " " + label + " " + HexFormat.of().formatHex(digest.digest()));
        for (String column : columns) out.println(column);
        StringBuilder melt = new StringBuilder();
        for (int z = 0; z < 16; z++) {
            for (int x = 0; x < 16; x++) {
                pos.set(cx * 16 + x, 63, cz * 16 + z);
                melt.append(biomes.manager.getBiome(pos).value().shouldMeltFrozenOceanIcebergSlightly(pos, 63) ? '1' : '0');
            }
        }
        out.println("surfacemelt " + prefix + " " + melt);
    }
}
