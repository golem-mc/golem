import java.io.PrintWriter;
import java.util.ArrayList;
import net.minecraft.SharedConstants;
import net.minecraft.core.RegistryAccess;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.LevelHeightAccessor;
import net.minecraft.world.level.biome.MultiNoiseBiomeSource;
import net.minecraft.world.level.biome.MultiNoiseBiomeSourceParameterLists;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.NoiseGeneratorSettings;
import net.minecraft.world.level.levelgen.structure.placement.RandomSpreadStructurePlacement;

// Pins actual generation stubs and saved buildings, including candidates
// rejected by the surrounding-biome check despite a valid centre biome.
public class MonumentStartsGolden {
    public static void main(String[] args) throws Exception {
        try { generate(args); } catch (Throwable e) {
            e.printStackTrace(new java.io.PrintStream(new java.io.FileOutputStream(java.io.FileDescriptor.err)));
            throw e;
        }
    }
    static void generate(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        RegistryAccess lookup;
        try (var resources = WorldgenSupport.resources()) {
            WorldgenSupport.bindTags(resources);
            lookup = (RegistryAccess) WorldgenSupport.loadWorld(resources);
        }
        var biomes = MultiNoiseBiomeSource.createFromPreset(lookup.lookupOrThrow(Registries.MULTI_NOISE_BIOME_SOURCE_PARAMETER_LIST).getOrThrow(MultiNoiseBiomeSourceParameterLists.OVERWORLD));
        var generator = new NoiseBasedChunkGenerator(biomes, lookup.lookupOrThrow(Registries.NOISE_SETTINGS).getOrThrow(NoiseGeneratorSettings.OVERWORLD));
        var monument = (net.minecraft.world.level.levelgen.structure.structures.OceanMonumentStructure) lookup.lookupOrThrow(Registries.STRUCTURE).getOrThrow(ResourceKey.create(Registries.STRUCTURE, Identifier.withDefaultNamespace("monument"))).value();
        var set = lookup.lookupOrThrow(Registries.STRUCTURE_SET).getOrThrow(ResourceKey.create(Registries.STRUCTURE_SET, Identifier.withDefaultNamespace("ocean_monuments"))).value();
        var placement = (RandomSpreadStructurePlacement) set.placement();
        try (PrintWriter out = new PrintWriter(args[0], "UTF-8")) {
            out.println("# Generated by MonumentStartsGolden.java from vanilla " + WorldgenSupport.version() + " OceanMonumentStructure.findGenerationPoint and StructurePiece.createTag.");
            for (long seed : new long[]{0, 12345, -7343414273836990780L}) {
                var random = WorldgenSupport.randomState(lookup, NoiseGeneratorSettings.OVERWORLD, seed);
                var candidates = new ArrayList<ChunkPos>();
                for (int x = -3; x <= 3; x++) {
                    for (int z = -3; z <= 3; z++) candidates.add(placement.getPotentialStructureChunk(seed, x * 32, z * 32));
                }
                candidates.add(new ChunkPos(-278, -16));
                candidates.add(new ChunkPos(111, 110));
                for (var chunk : candidates) {
                    var context = WorldgenSupport.structureContext(lookup, generator, biomes, random, null, seed, chunk,
                        LevelHeightAccessor.create(-64, 384), monument.biomes()::contains);
                    var stub = monument.findGenerationPoint(context);
                    // An empty stub is either check: onTopOfChunkCenter refuses a
                    // column that can hold no valid biome before the stub exists.
                    boolean surrounded = context.biomeResolver().getBiomesWithin(chunk.getBlockX(9), generator.getSeaLevel(), chunk.getBlockZ(9), 29)
                        .stream().allMatch(b -> b.is(net.minecraft.tags.BiomeTags.REQUIRED_OCEAN_MONUMENT_SURROUNDING));
                    if (stub.isEmpty()) {
                        out.printf("%d %d %d %s%n", seed, chunk.x(), chunk.z(), surrounded ? "centre" : "surrounding");
                    } else if (!monument.biomes().contains(biomes.getNoiseBiome(WorldgenSupport.climateSampler(random).sample(stub.get().position().getX() >> 2, stub.get().position().getY() >> 2, stub.get().position().getZ() >> 2)))) {
                        out.printf("%d %d %d centre%n", seed, chunk.x(), chunk.z());
                    } else {
                        var piece = stub.get().getPiecesBuilder().build().pieces().getFirst();
                        var tag = piece.createTag(null);
                        var box = piece.getBoundingBox();
                        out.printf("%d %d %d start %d %d %d %d %d %d %d%n", seed, chunk.x(), chunk.z(),
                            tag.getIntOr("O", -1), box.minX(), box.minY(), box.minZ(), box.maxX(), box.maxY(), box.maxZ());
                        if (!tag.getStringOr("id", "").equals("minecraft:omb") || tag.getIntOr("GD", -1) != 0 || tag.size() != 4) throw new IllegalStateException("Unexpected building data " + tag);
                    }
                }
            }
        }
    }
}
