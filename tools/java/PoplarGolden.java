import com.mojang.serialization.JsonOps;
import com.google.gson.JsonParser;
import java.io.PrintWriter;
import java.util.List;
import java.util.Optional;
import net.minecraft.SharedConstants;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.levelgen.feature.TreeFeature;
import net.minecraft.world.level.levelgen.feature.foliageplacers.FoliagePlacer;
import net.minecraft.world.level.levelgen.feature.foliageplacers.PoplarFoliagePlacer;
import net.minecraft.world.level.levelgen.feature.stateproviders.BlockStateProvider;
import net.minecraft.world.level.levelgen.feature.trunkplacers.PoplarTrunkPlacer;
import net.minecraft.util.valueproviders.ConstantInt;
import net.minecraft.util.valueproviders.UniformInt;
import net.minecraft.util.valueproviders.IntProviders;

// Runs the 26.3 poplar placers with oak providers, isolating their algorithms
// from the poplar block registry and the separate shelf-mushroom decorator.
// The terrain, proxy and digest are shared with the existing tree golden.
public class PoplarGolden {
    static TreeFeature tree(int variant) {
        return new TreeFeature(
            Holder.direct(variant == 0 ? BlockStateProvider.of(Blocks.OAK_LOG) : weighted("oak_log", "birch_log")),
            new PoplarTrunkPlacer(7, 4, 0, variant == 0 ? ConstantInt.of(4) : UniformInt.of(0, 8), UniformInt.of(1, 4)),
            Holder.direct(variant == 0 ? BlockStateProvider.of(Blocks.OAK_LEAVES) : weighted("oak_leaves", "birch_leaves")),
            new PoplarFoliagePlacer(IntProviders.codec(0, 16).parse(JsonOps.INSTANCE, JsonParser.parseString(
                "{\"type\":\"minecraft:weighted_list\",\"distribution\":[{\"data\":5,\"weight\":5},{\"data\":6,\"weight\":5},{\"data\":7,\"weight\":1},{\"data\":8,\"weight\":1}]}"
            )).getOrThrow(), ConstantInt.of(0), UniformInt.of(5, 6), 0.15f),
            Optional.empty(), new net.minecraft.world.level.levelgen.feature.featuresize.TwoLayersFeatureSize(1, 0, 2),
            List.of(), true, Holder.direct(BlockStateProvider.of(Blocks.DIRT)));
    }

    static BlockStateProvider weighted(String first, String second) {
        return BlockStateProvider.DIRECT_CODEC.parse(JsonOps.INSTANCE, JsonParser.parseString(
            "{\"type\":\"minecraft:weighted\",\"entries\":[{\"data\":\"minecraft:" + first + "\",\"weight\":2},{\"data\":\"minecraft:" + second + "\",\"weight\":3}]}"
        )).getOrThrow();
    }

    static void canopyObstacles(OverworldTreeGolden.Level level, int k) {
        if (k < 12) return;
        level.changed.put(new BlockPos(8, 81, 8).asLong(), Blocks.WATER.defaultBlockState());
        level.changed.put(new BlockPos(9, 81, 8).asLong(), Blocks.OAK_LEAVES.defaultBlockState().setValue(net.minecraft.world.level.block.LeavesBlock.PERSISTENT, true));
        level.changed.put(new BlockPos(8, 82, 9).asLong(), Blocks.STONE.defaultBlockState());
        level.changed.put(new BlockPos(7, 82, 8).asLong(), Blocks.OAK_LEAVES.defaultBlockState().setValue(net.minecraft.world.level.block.LeavesBlock.DISTANCE, 2));
    }

    static net.minecraft.server.packs.resources.MultiPackResourceManager setup() throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        var resources = WorldgenSupport.resources();
        WorldgenSupport.bindTags(resources);
        OverworldTreeGolden.grass = Blocks.GRASS_BLOCK.defaultBlockState();
        OverworldTreeGolden.dirt = Blocks.DIRT.defaultBlockState();
        OverworldTreeGolden.stone = Blocks.STONE.defaultBlockState();
        OverworldTreeGolden.sand = Blocks.SAND.defaultBlockState();
        OverworldTreeGolden.water = Blocks.WATER.defaultBlockState();
        OverworldTreeGolden.bedrock = Blocks.BEDROCK.defaultBlockState();
        OverworldTreeGolden.air = Blocks.AIR.defaultBlockState();
        return resources;
    }

    public static void main(String[] args) throws Exception {
        var resources = setup();
        var lookup = WorldgenSupport.loadWorld(resources);
        var generator = OverworldTreeGolden.generator(lookup);
        OverworldTreeGolden.generatorOfLevel = generator;
        var storage = net.minecraft.world.level.storage.LevelStorageSource.createDefault(java.nio.file.Path.of("poplar-golden-worlds")).createAccess("test");
        OverworldTreeGolden.templateLevel = WorldgenSupport.templateLevel(resources, storage);
        OverworldTreeGolden.prepareLevel();
        try (PrintWriter out = new PrintWriter(args[0], "UTF-8")) {
            out.println("# Generated by tools/java/PoplarGolden.java from vanilla " + WorldgenSupport.version() + ". DO NOT EDIT.");
            out.println("# Oak/birch providers isolate poplar placers; no decorators. Digests include every changed state; tail is the next random int.");
            for (int variant = 0; variant < 2; variant++) {
                TreeFeature tree = tree(variant);
                var config = TreeFeature.CODEC.codec().encodeStart(lookup.createSerializationContext(JsonOps.INSTANCE), tree).getOrThrow();
                out.println("config " + variant + " " + config);
                for (long seed : new long[]{0L, 1L, 2L, 17L, 12345L, -424242L, Long.MIN_VALUE, Long.MAX_VALUE}) {
                    for (int k = 0; k < 4; k++) {
                        int cx = k == 0 ? 0 : -2, cz = k == 0 ? 0 : 3;
                        int x = cx * 16 + (k == 2 ? 15 : 3), z = cz * 16 + (k == 2 ? 15 : 7);
                        int y = k == 3 ? 313 : 80;
                        var level = new OverworldTreeGolden.Level(lookup, seed, cx, cz);
                        // An obstruction checks TreeFeature's free-height refusal.
                        if (k == 1) level.changed.put(new BlockPos(x, y + 4, z).asLong(), Blocks.STONE.defaultBlockState());
                        var random = OverworldTreeGolden.random(seed, cx, cz, 3, 8);
                        boolean placed = WorldgenSupport.place(tree, OverworldTreeGolden.proxy(level), generator, random, new BlockPos(x, y, z));
                        out.println("tree " + variant + " " + seed + " " + k + " " + (placed ? 1 : 0) + " " + OverworldTreeGolden.digest(level) + " " + random.nextInt());
                    }
                }
            }
            for (int k = 0; k < 24; k++) {
                TreeFeature tree = tree(k % 2);
                var level = new OverworldTreeGolden.Level(lookup, k, 0, 0);
                level.changed.put(new BlockPos(8, 82, 8).asLong(), Blocks.STONE.defaultBlockState());
                level.changed.put(new BlockPos(8, 85, 7).asLong(), Blocks.STONE.defaultBlockState());
                var random = OverworldTreeGolden.random(k, 0, 0, 3, 8);
                var attachments = tree.trunkPlacer().placeTrunk(OverworldTreeGolden.proxy(level),
                    (pos, state) -> level.changed.put(pos.asLong(), state), random, 1 + k % 12, new BlockPos(8, 80, 8), tree);
                if (attachments.size() != 1) throw new IllegalStateException("unexpected poplar attachments");
                var a = attachments.getFirst();
                out.println("trunk " + k + " " + a.pos().getY() + " " + a.radiusOffsetXZ() + " " + a.doubleTrunk() + " " + OverworldTreeGolden.digest(level) + " " + random.nextInt());
            }
            // Independent canopy cases exercise signed corners, partial rows,
            // double trunks, attachment offsets and sideways logs at large radii.
            for (int k = 0; k < 24; k++) {
                int radius = 3 + k % 6, height = 5 + k % 3;
                int offset = k % 3 - 1, heightOffset = k % 2;
                boolean doubleTrunk = (k & 2) != 0;
                float holes = new float[]{0.0f, 0.15f, 1.0f}[k % 3];
                var foliage = new PoplarFoliagePlacer(ConstantInt.of(radius), ConstantInt.of(offset), ConstantInt.of(height), holes);
                var level = new OverworldTreeGolden.Level(lookup, k, 0, 0);
                canopyObstacles(level, k);
                var random = OverworldTreeGolden.random(k, 0, 0, 3, 8);
                int size = doubleTrunk ? 2 : 1;
                var attachment = new FoliagePlacer.FoliageAttachment(new BlockPos(8, 80, 8), k % 2, heightOffset, size, size);
                var setter = new FoliagePlacer.FoliageSetter() {
                    public void set(BlockPos p, net.minecraft.world.level.block.state.BlockState state) { level.changed.put(p.asLong(), state); }
                    public boolean isSet(BlockPos p) { return level.changed.containsKey(p.asLong()); }
                };
                foliage.createFoliage(OverworldTreeGolden.proxy(level), setter, random, tree(k % 2), 10, attachment, height, radius);
                out.println("foliage " + k + " " + OverworldTreeGolden.digest(level) + " " + random.nextInt());
            }
        }
        storage.close();
    }
}
